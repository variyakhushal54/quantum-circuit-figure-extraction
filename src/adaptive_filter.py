#!/usr/bin/env python3
"""
Adaptive Filter using Learned Patterns
This module loads the knowledge file (generated by learning from valid circuits)
and uses it to score new images. It works like a specialized judge.
"""

import os
import json
import cv2
import numpy as np
import re

class AdaptiveCircuitFilter:
    """
    Main filter class.
    It loads the 'learned_circuit_patterns.json' file and checks if new images match those patterns.
    """
    
    def __init__(self, knowledge_file=os.path.join("data", "learned_circuit_patterns.json")):
        """
        Load the learned stats (like average line counts, common caption words).
        """
        if not os.path.exists(knowledge_file):
            raise FileNotFoundError(f"Run learn_from_circuits.py first to generate {knowledge_file}")
        
        with open(knowledge_file, 'r', encoding='utf-8-sig') as f:
            self.knowledge = json.load(f)
        
        # Stats about visual features (mean, std dev)
        self.visual_stats = self.knowledge['visual_features']['statistics']
        self.caption_patterns = self.knowledge['caption_patterns']
        
        # Common phrases found in valid circuit captions
        self.learned_bigrams = [phrase for phrase, _ in self.caption_patterns['top_bigrams']]
        self.learned_trigrams = [phrase for phrase, _ in self.caption_patterns['top_trigrams']]
        
        print(f"✓ Loaded learned patterns from {knowledge_file}")
        print(f"  Visual features: {len(self.visual_stats)} dimensions")
        print(f"  Caption phrases: {len(self.learned_bigrams)} bigrams")
    
    def extract_features(self, image_path_or_array):
        """
        Analyze an image and extract the same features we used for training.
        :param image_path_or_array: File path string or OpenCV image object
        :return: Dictionary of features (e.g., {'h_line_count': 5, ...})
        """
        if isinstance(image_path_or_array, str):
            img = cv2.imread(image_path_or_array)
        else:
            img = image_path_or_array
        
        if img is None:
            return {}
        
        # Convert to grayscale for analysis
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        h, w = gray.shape
        
        features = {}
        
        # --- Structural Analysis (Lines) ---
        # Detect edges first
        edges = cv2.Canny(gray, 50, 150)
        # Find straight lines (wires)
        lines = cv2.HoughLinesP(edges, 1, np.pi/180, threshold=50,
                               minLineLength=int(w * 0.2), maxLineGap=20)
        
        h_lines, v_lines = 0, 0
        if lines is not None:
            for line in lines:
                x1, y1, x2, y2 = line[0]
                # If y-coordinates are close, it's horizontal
                if abs(y1 - y2) < 10:
                    h_lines += 1
                # If x-coordinates are close, it's vertical
                if abs(x1 - x2) < 10:
                    v_lines += 1
        
        features['h_line_count'] = h_lines
        features['v_line_count'] = v_lines
        # How "busy" is the image? (text/noise has high density)
        features['edge_density'] = np.sum(edges > 0) / edges.size
        
        # --- Shape Analysis (Gates) ---
        # Find contours (blobs)
        contours, _ = cv2.findContours(edges, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        box_like, circle_like = 0, 0
        for cnt in contours:
            area = cv2.contourArea(cnt)
            # Filter noise (too small) and huge borders (too large)
            if 100 < area < 5000:
                perimeter = cv2.arcLength(cnt, True)
                if perimeter > 0:
                    # Circularity metric: 1.0 is a perfect circle
                    circularity = 4 * np.pi * area / (perimeter ** 2)
                    if circularity > 0.7:
                        circle_like += 1 # Likely a control node or qubit
                    else:
                        box_like += 1 # Likely a gate box (H, X, etc.)
        
        features['box_count'] = box_like
        features['circle_count'] = circle_like
        
        # --- Color Analysis ---
        # Convert to HSV to check saturation (colorfulness) and value (brightness)
        hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
        features['avg_saturation'] = np.mean(hsv[:, :, 1]) / 255.0 # 0=gray, 1=vibrant
        features['avg_brightness'] = np.mean(hsv[:, :, 2]) / 255.0
        features['aspect_ratio'] = w / h if h > 0 else 1.0
        
        return features
    
    def score_visual_similarity(self, image):
        """
        Compare this image's features to the 'average' valid circuit.
        Uses Z-score (standard deviation) to measure distance.
        :return: Score 0-100 (100 is a perfect match to the average)
        """
        features = self.extract_features(image)
        if not features:
            return 0
        
        score = 0
        max_score = 0
        
        for feat_name, value in features.items():
            if feat_name not in self.visual_stats:
                continue
            
            # Get learned stats for this feature
            stats = self.visual_stats[feat_name]
            mean = stats['mean']
            std = stats['std']
            
            # Z-score: how many standard deviations is this value from the mean?
            if std > 0:
                z_score = abs(value - mean) / std
                # Start at 100, subtract points for being far away
                # If > 3 std devs away, score is 0
                feat_score = max(0, 100 - (z_score * 33.3))
            else:
                # If std is 0 (constant feature), exact match required
                feat_score = 100 if value == mean else 0
            
            score += feat_score
            max_score += 100
        
        # Normalize to 0-100
        return (score / max_score *100) if max_score > 0 else 0
    
    def score_caption_similarity(self, caption):
        """
        Check if the caption contains common "circuit-y" phrases.
        :return: Score 0-100
        """
        if not caption:
            return 0
        
        caption_lower = caption.lower()
        words = re.findall(r'\b\w+\b', caption_lower)
        
        score = 0
        
        # Generate bigrams (2-word pairs) from caption
        caption_bigrams = []
        for i in range(len(words) - 1):
            caption_bigrams.append(f"{words[i]} {words[i+1]}")
        
        # Generate trigrams (3-word sequences)
        caption_trigrams = []
        for i in range(len(words) - 2):
            caption_trigrams.append(f"{words[i]} {words[i+1]} {words[i+2]}")
        
        # Check how many match our learned list
        bigram_matches = sum(1 for bg in caption_bigrams if bg in self.learned_bigrams)
        trigram_matches = sum(1 for tg in caption_trigrams if tg in self.learned_trigrams)
        
        # Calculate a ratio score
        if len(caption_bigrams) > 0:
            score += (bigram_matches / len(caption_bigrams)) * 60
        
        if len(caption_trigrams) > 0:
            score += (trigram_matches / len(caption_trigrams)) * 40
        
        return min(100, score)
    
    def is_circuit(self, image, caption=None, threshold_visual=40, threshold_caption=30):
        """
        Main decision function.
        Returns true if the image looks like a circuit (visually or caption-wise).
        """
        visual_score = self.score_visual_similarity(image)
        caption_score = self.score_caption_similarity(caption) if caption else 0
        
        # Decision Logic:
        # 1. High visual match -> Pass
        # 2. Moderate visual match AND good caption -> Pass
        visual_pass = visual_score >= threshold_visual
        caption_pass = caption_score >= threshold_caption
        moderate_visual = visual_score >= 30
        
        is_valid = visual_pass or (moderate_visual and caption_pass)
        
        if is_valid:
            reason = f"learned_match (V:{visual_score:.0f} C:{caption_score:.0f})"
        else:
            reason = f"no_match (V:{visual_score:.0f} C:{caption_score:.0f})"
        
        return {
            "is_valid": is_valid,
            "visual_score": visual_score,
            "caption_score": caption_score,
            "reason": reason
        }

# If run directly as a script (for testing)
if __name__ == "__main__":
    import sys
    
    if len(sys.argv) < 2:
        print("Usage: python adaptive_filter.py <image_path> [caption]")
        sys.exit(1)
    
    image_path = sys.argv[1]
    caption = sys.argv[2] if len(sys.argv) > 2 else None
    
    filter = AdaptiveCircuitFilter()
    result = filter.is_circuit(image_path, caption)
    
    print(f"\nResults:")
    print(f"  Is Circuit: {result['is_valid']}")
    print(f"  Visual Score: {result['visual_score']:.1f}/100")
    print(f"  Caption Score: {result['caption_score']:.1f}/100")
    print(f"  Reason: {result['reason']}")
